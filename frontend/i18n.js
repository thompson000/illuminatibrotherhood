const i18n = {
  current: 'en',
  supported: I18N_LANGUAGES,
  strings: I18N_STRINGS,
  init() {
    const stored = localStorage.getItem('brotherhood_language');
    this.current = stored && this.strings[stored] ? stored : 'en';
    this.applyLanguage();
    this.buildLanguageMenu();
  },
  get currentData() {
    return this.strings[this.current] || this.strings.en;
  },
  t(key, params) {
    const value = this.currentData[key] ?? this.strings.en[key] ?? '';
    if (!params) return value;
    return Object.keys(params).reduce((result, paramKey) => result.replace(new RegExp(`{${paramKey}}`, 'g'), params[paramKey]), value);
  },
  setLanguage(code) {
    if (!this.strings[code]) return;
    this.current = code;
    localStorage.setItem('brotherhood_language', code);
    this.applyLanguage();
  },
  applyLanguage() {
    document.documentElement.lang = this.current;
    document.documentElement.dir = I18N_LANGUAGES.find(l => l.code === this.current)?.dir || 'ltr';
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.dataset.i18n;
      if (!key) return;
      const text = this.t(key);
      if (text !== '') el.textContent = text;
    });
    document.querySelectorAll('[data-i18n-html]').forEach(el => {
      const key = el.dataset.i18nHtml;
      if (!key) return;
      const text = this.t(key);
      if (text !== '') el.innerHTML = text;
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.dataset.i18nPlaceholder;
      if (!key) return;
      const text = this.t(key);
      if (text !== '') el.placeholder = text;
    });
    document.querySelectorAll('[data-i18n-value]').forEach(el => {
      const key = el.dataset.i18nValue;
      if (!key) return;
      const text = this.t(key);
      if (text !== '') el.value = text;
    });
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
      const key = el.dataset.i18nTitle;
      if (!key) return;
      const text = this.t(key);
      if (text !== '') el.title = text;
    });
    document.querySelectorAll('[data-i18n-alt]').forEach(el => {
      const key = el.dataset.i18nAlt;
      if (!key) return;
      const text = this.t(key);
      if (text !== '') el.alt = text;
    });
    document.querySelectorAll('[data-i18n-aria]').forEach(el => {
      const key = el.dataset.i18nAria;
      if (!key) return;
      const text = this.t(key);
      if (text !== '') el.setAttribute('aria-label', text);
    });
    const title = document.querySelector('title[data-i18n]');
    if (title) title.textContent = this.t(title.dataset.i18n);
    const metaDesc = document.querySelector('meta[name="description"][data-i18n]');
    if (metaDesc) metaDesc.setAttribute('content', this.t(metaDesc.dataset.i18n));
    this.updateLanguageLabel();
    this.updateActiveLanguageOption();
  },
  updateLanguageLabel() {
    const buttonLabel = document.getElementById('languageLabel');
    const selected = I18N_LANGUAGES.find(l => l.code === this.current) || I18N_LANGUAGES[0];
    if (buttonLabel) {
      buttonLabel.textContent = `${selected.flag} ${selected.name}`;
    }
  },
  buildLanguageMenu() {
    const menu = document.getElementById('languageMenu');
    if (!menu) return;
    menu.innerHTML = I18N_LANGUAGES.map(lang => `
      <button type="button" class="language-option" role="option" data-lang="${lang.code}" aria-selected="${lang.code === this.current ? 'true' : 'false'}">
        <span class="language-option-flag">${lang.flag}</span>
        <span class="language-option-name">${lang.name}</span>
      </button>
    `).join('');
    this.attachLanguageMenuListeners();
  },
  attachLanguageMenuListeners() {
    const toggle = document.getElementById('languageToggle');
    const menu = document.getElementById('languageMenu');
    if (!toggle || !menu) return;
    toggle.addEventListener('click', (event) => {
      const expanded = toggle.getAttribute('aria-expanded') === 'true';
      toggle.setAttribute('aria-expanded', expanded ? 'false' : 'true');
      menu.classList.toggle('open', !expanded);
      if (!expanded) {
        menu.querySelector('.language-option[aria-selected="true"]')?.focus();
      }
      event.stopPropagation();
    });
    menu.querySelectorAll('.language-option').forEach(button => {
      button.addEventListener('click', () => {
        this.setLanguage(button.dataset.lang);
        this.closeLanguageMenu();
      });
      button.addEventListener('keydown', (event) => {
        const options = Array.from(menu.querySelectorAll('.language-option'));
        const currentIndex = options.indexOf(event.currentTarget);
        if (event.key === 'ArrowDown') {
          event.preventDefault();
          options[(currentIndex + 1) % options.length].focus();
        } else if (event.key === 'ArrowUp') {
          event.preventDefault();
          options[(currentIndex - 1 + options.length) % options.length].focus();
        } else if (event.key === 'Escape') {
          this.closeLanguageMenu();
          toggle.focus();
        }
      });
    });
    document.addEventListener('click', (event) => {
      if (!menu.contains(event.target) && event.target !== toggle) {
        this.closeLanguageMenu();
      }
    });
    document.addEventListener('keydown', (event) => {
      if (event.key === 'Escape') {
        this.closeLanguageMenu();
      }
    });
  },
  closeLanguageMenu() {
    const toggle = document.getElementById('languageToggle');
    const menu = document.getElementById('languageMenu');
    if (!toggle || !menu) return;
    toggle.setAttribute('aria-expanded', 'false');
    menu.classList.remove('open');
  },
  updateActiveLanguageOption() {
    const menu = document.getElementById('languageMenu');
    if (!menu) return;
    menu.querySelectorAll('.language-option').forEach(button => {
      const isActive = button.dataset.lang === this.current;
      button.setAttribute('aria-selected', isActive ? 'true' : 'false');
      button.classList.toggle('active', isActive);
    });
  },
};

window.i18n = i18n;

document.addEventListener('DOMContentLoaded', () => {
  if (window.i18n) {
    window.i18n.init();
  }
});
